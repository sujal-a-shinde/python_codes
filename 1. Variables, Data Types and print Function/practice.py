"""
Q1: Take two numbers as input from the user. Print their sum, difference,
product, and remainder.
"""

num_1 = int(input("Enter your First Number : "))
num_2 = int(input("Enter your Second Number : "))

print(f"The Sum of the Numbers are : {num_1+num_2}")
print(f"The Difference of the Numbers are : {num_1-num_2}")
print(f"The Product of the Numbers are : {num_1*num_2}")
print(f"The Remainder of the Numbers are : {num_1%num_2}")
