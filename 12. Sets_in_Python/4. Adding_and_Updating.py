# Use add() for single elements

pythonfruits = {"apple", "mango"}
pythonfruits.add("kiwi")
pythonfruits.add("grape")
print(pythonfruits)


# use update() for multiple elements from an iterables

pythonfruits1 = {"apple", "mango"}
pythonfruits1.update(["kiwi", "grape", "lichi"])
print(pythonfruits1)
