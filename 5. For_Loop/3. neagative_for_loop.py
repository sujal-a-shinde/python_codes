# 10 to 1

for i in range(10, 0, -1):
    print(i, end=" ")

# vice versa

for i in range(1, 11, -1):
    print(i, end=" ")

# left side
for i in range(1, -11, -1):
    print(i, end=" ")

# conditional statement
for i in range(100, 0, -1):
    if i % 2 == 0 and i % 3 == 0:
        print(i, end=" ")
